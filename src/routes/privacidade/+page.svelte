      <h1>Política de Privacidade — Não Mexe Aí</h1>
      <p class="updated">Última atualização: 13 de agosto de 2026</p>

      <p>
        A presente Política de Privacidade explica como o Não Mexe Aí trata informações relacionadas
        aos usuários do aplicativo e do site.
      </p>
      <p>Esta política deve ser lida juntamente com os Termos de Uso.</p>

      <h2>1. Informações fornecidas pelo usuário</h2>
      <p>
        O aplicativo Não Mexe Aí não exige criação de conta ou login para utilização das
        funcionalidades principais.
      </p>
      <p>
        Durante o período de teste fechado, o usuário poderá voluntariamente fornecer informações
        através do site, incluindo:
      </p>
      <ul>
        <li>nome;</li>
        <li>endereço de e-mail da Conta Google;</li>
        <li>mensagens ou feedback enviados voluntariamente.</li>
      </ul>
      <p>
        Esses dados serão utilizados para gerenciamento do teste fechado, comunicação relacionada ao
        aplicativo e suporte.
      </p>

      <h2>2. Informações processadas automaticamente</h2>
      <p>
        O aplicativo pode utilizar serviços e SDKs de terceiros que processam determinadas
        informações técnicas necessárias ao funcionamento, segurança, publicidade e diagnóstico.
      </p>
      <p>
        Dependendo do serviço e das configurações do dispositivo, essas informações podem incluir:
      </p>
      <ul>
        <li>modelo do dispositivo;</li>
        <li>versão do Android;</li>
        <li>endereço IP;</li>
        <li>identificadores relacionados ao dispositivo ou publicidade;</li>
        <li>informações de desempenho;</li>
        <li>informações sobre falhas;</li>
        <li>interação com anúncios.</li>
      </ul>

      <h2>3. Publicidade</h2>
      <p>O Não Mexe Aí utiliza ou poderá utilizar o Google AdMob para apresentar anúncios.</p>
      <p>
        O Google e seus parceiros podem processar informações relacionadas ao dispositivo e à
        interação com anúncios para fornecer, medir e proteger os serviços de publicidade.
      </p>
      <p>
        A utilização dessas informações também está sujeita às políticas e configurações de
        privacidade do Google.
      </p>
      <p>
        Quando exigido pela legislação aplicável, mecanismos de consentimento poderão ser
        apresentados ao usuário.
      </p>

      <h2>4. Anúncios recompensados</h2>
      <p>
        Determinadas funcionalidades do aplicativo podem ser liberadas temporariamente quando o
        usuário escolhe voluntariamente assistir a um anúncio recompensado.
      </p>
      <p>A visualização desse tipo de anúncio é opcional.</p>
      <p>
        Caso o usuário não deseje visualizar o anúncio, poderá continuar utilizando as
        funcionalidades disponíveis gratuitamente.
      </p>

      <h2>5. Serviço de Acessibilidade</h2>
      <p>
        Algumas funcionalidades podem depender do serviço de acessibilidade do Android.
      </p>
      <p>
        Caso esse recurso seja utilizado, o aplicativo apresentará uma explicação antes de solicitar
        sua ativação.
      </p>
      <p>
        O recurso será utilizado apenas para executar funcionalidades apresentadas ao usuário e
        iniciadas por ele.
      </p>
      <p>O Não Mexe Aí não deve utilizar informações acessadas através do serviço de acessibilidade para:</p>
      <ul>
        <li>capturar senhas;</li>
        <li>coletar credenciais;</li>
        <li>ler mensagens privadas para fins comerciais;</li>
        <li>comercializar dados;</li>
        <li>direcionar publicidade com base em conteúdo acessado pelo serviço;</li>
        <li>criar perfis pessoais com base em conteúdo observado através do serviço.</li>
      </ul>
      <p>
        O usuário poderá desativar o serviço através das configurações de acessibilidade do Android.
      </p>

      <h2>6. Dados do teste fechado</h2>
      <p>
        Os e-mails enviados através da landing page poderão ser utilizados para adicionar usuários à
        lista de participantes do teste fechado do Google Play.
      </p>
      <p>Também poderemos enviar mensagens relacionadas a:</p>
      <ul>
        <li>acesso ao beta;</li>
        <li>instruções de instalação;</li>
        <li>atualizações importantes;</li>
        <li>solicitação de feedback;</li>
        <li>disponibilidade pública do aplicativo.</li>
      </ul>
      <p>Esses dados não serão vendidos.</p>

      <h2>7. Compartilhamento com terceiros</h2>
      <p>
        Informações poderão ser processadas por prestadores necessários ao funcionamento do serviço,
        como:
      </p>
      <ul>
        <li>Google Play;</li>
        <li>Google AdMob;</li>
        <li>provedores de hospedagem;</li>
        <li>serviços utilizados para envio de e-mails;</li>
        <li>serviços de análise ou diagnóstico, caso implementados.</li>
      </ul>
      <p>Cada prestador poderá possuir sua própria política de privacidade.</p>

      <h2>8. Retenção</h2>
      <p>
        Os dados fornecidos para participação no beta serão mantidos somente pelo período necessário
        às finalidades descritas nesta Política ou conforme exigido por obrigação legal.
      </p>
      <p>
        O usuário poderá solicitar exclusão de informações diretamente fornecidas ao Não Mexe Aí
        através do canal de contato indicado abaixo.
      </p>

      <h2>9. Segurança</h2>
      <p>
        Adotamos medidas técnicas razoáveis para proteger as informações sob nosso controle contra
        acesso não autorizado, perda, alteração ou divulgação indevida.
      </p>
      <p>Nenhum sistema, entretanto, pode garantir segurança absoluta.</p>

      <h2>10. Crianças e adolescentes</h2>
      <p>
        O Não Mexe Aí não deve ser utilizado para coletar intencionalmente informações pessoais de
        crianças.
      </p>
      <p>
        Caso a utilização do aplicativo seja direcionada ou disponibilizada a menores de idade,
        deverão ser observadas as regras aplicáveis do Google Play e da legislação brasileira.
      </p>

      <h2>11. Direitos do titular</h2>
      <p>
        Nos termos da legislação aplicável, inclusive a Lei Geral de Proteção de Dados Pessoais —
        LGPD, o usuário poderá solicitar, quando aplicável:
      </p>
      <ul>
        <li>confirmação da existência de tratamento;</li>
        <li>acesso aos dados;</li>
        <li>correção;</li>
        <li>exclusão;</li>
        <li>informações sobre compartilhamento;</li>
        <li>revogação de consentimento.</li>
      </ul>
      <p>Solicitações podem ser feitas através do canal de contato indicado abaixo.</p>

      <h2>12. Alterações desta Política</h2>
      <p>
        Esta Política poderá ser atualizada para refletir alterações no aplicativo, legislação ou
        serviços utilizados.
      </p>
      <p>A data da versão mais recente será indicada no início desta página.</p>

